#!/usr/bin/env node
/**
 * Build-time asset pipeline.
 *
 * Converts the original starter-kit binaries into runtime-friendly, bundler-safe
 * modules so the game never depends on a filesystem fetch at runtime:
 *
 *  - GLB models  -> base64 modules (parsed lazily with GLTFLoader.parse)
 *  - PNG albedo  -> raw RGBA pixels (128x128, decoded here with ImageMagick)
 *  - SVG icons   -> sanitized SVG markup modules
 *  - brand art   -> PNG icons / splash generated from SVG sources
 *
 * Requires `rsvg-convert` and/or ImageMagick `convert` on the build machine.
 * Generated output is committed, so device builds need no extra tooling.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const KIT = join(ROOT, 'docs/AFTERLIGHT_Starter_Assets/assets');
const GENERATED = join(ROOT, 'src/game/assets/generated');
const BRAND_SRC = join(ROOT, 'assets/branding');
const BRAND_OUT = join(ROOT, 'assets');

const has = (bin) => {
  try {
    execFileSync('which', [bin], { stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
};

mkdirSync(GENERATED, { recursive: true });

const banner = '// AUTO-GENERATED by tools/assets/build-assets.mjs — do not edit by hand.\n';

// ── Models ────────────────────────────────────────────────────────────────
const models = ['stylized_tree', 'stylized_rock', 'starter_cabin'];
let modelsTs = `${banner}\n/** Base64-encoded GLB payloads (original AFTERLIGHT starter kit). */\nexport const MODEL_GLB_BASE64 = {\n`;
for (const id of models) {
  const b64 = readFileSync(join(KIT, 'models', `${id}.glb`)).toString('base64');
  modelsTs += `  ${id}: '${b64}',\n`;
}
modelsTs += '} as const;\n\nexport type ModelId = keyof typeof MODEL_GLB_BASE64;\n';
writeFileSync(join(GENERATED, 'models.ts'), modelsTs);

// ── Textures ──────────────────────────────────────────────────────────────
const textures = ['grass_albedo', 'bark_albedo', 'stone_albedo', 'weathered_wood_albedo'];
const SIZE = 128;
let texturesTs = `${banner}\n/**\n * Raw RGBA pixels (128x128) decoded from the starter-kit albedo PNGs.\n * Embedded so textures load synchronously on device as THREE.DataTexture.\n */\nexport const TEXTURE_RGBA_BASE64 = {\n`;
const convert = has('convert') ? 'convert' : has('magick') ? 'magick' : null;
for (const id of textures) {
  let raw;
  if (convert) {
    raw = execFileSync(convert, [
      join(KIT, 'textures', `${id}.png`),
      '-resize',
      `${SIZE}x${SIZE}!`,
      '-depth',
      '8',
      'RGBA:-',
    ], { maxBuffer: 64 * 1024 * 1024 });
  } else {
    throw new Error('ImageMagick is required to rebuild textures (convert/magick).');
  }
  if (raw.length !== SIZE * SIZE * 4) throw new Error(`Unexpected pixel size for ${id}: ${raw.length}`);
  texturesTs += `  ${id}: '${raw.toString('base64')}',\n`;
}
texturesTs += `} as const;\n\nexport const TEXTURE_SIZE = ${SIZE};\n\nexport type TextureId = keyof typeof TEXTURE_RGBA_BASE64;\n`;
writeFileSync(join(GENERATED, 'textures.ts'), texturesTs);

// ── Icons ─────────────────────────────────────────────────────────────────
const iconNames = [
  'wood', 'stone', 'food', 'water', 'fiber', 'scrap', 'health', 'home', 'map', 'craft', 'energy', 'backpack',
];
let iconsTs = `${banner}\n/** Monochrome SVG icons from the starter kit. */\nexport const KIT_ICONS: Record<string, string> = {\n`;
for (const name of iconNames) {
  const svg = readFileSync(join(KIT, 'ui/icons', `${name}.svg`), 'utf8')
    .replace(/\s+/g, ' ')
    .replace(/>\s+</g, '><')
    .trim();
  iconsTs += `  ${name}: ${JSON.stringify(svg)},\n`;
}
iconsTs += '};\n';
writeFileSync(join(GENERATED, 'icons.ts'), iconsTs);

// ── Brand artwork ─────────────────────────────────────────────────────────
if (has('rsvg-convert')) {
  const raster = (src, out, width, height) => {
    execFileSync('rsvg-convert', ['-w', String(width), '-h', String(height), '-o', out, join(BRAND_SRC, src)]);
    console.log(`  ✓ ${out.replace(ROOT + '/', '')} (${width}x${height})`);
  };
  raster('menu_keyart.svg', join(BRAND_OUT, 'branding/menu_keyart.png'), 1600, 900);
  raster('icon.svg', join(BRAND_OUT, 'icon.png'), 1024, 1024);
  raster('icon_foreground.svg', join(BRAND_OUT, 'android-icon-foreground.png'), 1024, 1024);
  raster('icon_monochrome.svg', join(BRAND_OUT, 'android-icon-monochrome.png'), 1024, 1024);
  raster('splash.svg', join(BRAND_OUT, 'splash-icon.png'), 512, 512);
  raster('icon.svg', join(BRAND_OUT, 'favicon.png'), 64, 64);
} else {
  console.warn('! rsvg-convert not found — brand PNGs left untouched');
}

console.log(`\nAssets built:\n  models: ${models.length}\n  textures: ${textures.length} @ ${SIZE}px\n  icons: ${iconNames.length}`);
